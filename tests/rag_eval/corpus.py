def _monthly_series() -> Dict[str, str]:
    """按月份循环生成「看起来一样」的过程资料。

    真实项目的资料量主要来自这类按期报送的月报与台账：页数多、句式重复、
    每页都命中「项目/进度/金额/验收」等步骤词表，但绝大多数与当前问题无关。
    这类文本正是关键词打分失效的地方——分数都差不多，排序等于随机。
    """
    months = [f"2024 年 {m} 月" for m in range(3, 13)] + [f"2025 年 {m} 月" for m in range(1, 10)]
    report_pages, ledger_pages = [], []
    for index, month in enumerate(months, 1):
        report_pages.append(
            f"【PDF 第{index}页】\n"
            f"{month}监理月报：本月完成管道敷设 {0.9 + index * 0.07:.2f} 公里，"
            f"累计完成 {2.1 + index * 0.86:.2f} 公里。\n"
            f"本月召开监理例会 1 次，开展安全检查 4 次，旁站 {30 + index} 次。\n"
            f"质量评价：本月验收检验批 {12 + index} 个，合格率 100%，未发生质量事故。\n"
            f"进度说明：按计划推进，存在局部工序衔接不畅，已要求施工单位增加班组。\n"
            f"下月计划：完成剩余管段敷设与检查井砌筑，配合建设单位推进征拆协调。"
        )
        ledger_pages.append(
            f"【PDF 第{index}页】\n"
            f"{month}支付台账：本期申报金额 {180 + index * 23}.50 万元，"
            f"核定支付 {170 + index * 21}.20 万元。\n"
            f"支付依据：月度计量单、监理签认单、发票及合同复印件。\n"
            f"累计支付 {320.4 + index * 208.6:.1f} 万元，资金来源为市级财政拨款与区级配套。\n"
            f"备注：本月无超概算支出，无新增变更。"
        )
    return {
        "06_监理月报汇编.txt": "\n\n".join(report_pages),
        "07_支付台账汇编.txt": "\n\n".join(ledger_pages),
    }


DOCS.update(_monthly_series())

